"""Offline Singapore catalogue for a one- or two-day demo.

Hours, prices, access, and diet flags are curated illustrations with a
source note and a last-reviewed date. They are not a live feed. Missing
hours or prices stay missing. Crowd levels are estimates.
"""

from __future__ import annotations

from triper.models import INTERESTS, WEEKDAYS, Venue, parse_hm

SOURCE = (
    "Illustrative offline catalogue for the Triper demo "
    "(not a live OneMap, LTA DataMall, or data.gov.sg feed)"
)


def _tags(**values: float) -> dict[str, float]:
    tags = {key: 0.0 for key in INTERESTS}
    tags.update(values)
    return tags


def _hours(open_hm: str, close_hm: str, closed: tuple[str, ...] = ()) -> dict[str, tuple[int, int] | None]:
    span = (parse_hm(open_hm), parse_hm(close_hm))
    return {day: None if day in closed else span for day in WEEKDAYS}


def _venue(
    id_: str,
    name: str,
    area: str,
    lat: float,
    lon: float,
    category: str,
    tags: dict[str, float],
    duration: int,
    price: float | None,
    hours: dict[str, tuple[int, int] | None] | None,
    *,
    aliases: list[str] | None = None,
    diets: set[str] | None = None,
    serves_food: bool = False,
    wheelchair: bool = True,
    step_free: bool = True,
    crowd: float = 0.5,
    indoor: bool = True,
    weather: bool = False,
    updated: str = "2026-09-01",
    notes: str = "",
) -> Venue:
    return Venue(
        id=id_,
        name=name,
        aliases=aliases or [],
        area=area,
        lat=lat,
        lon=lon,
        category=category,
        tags=tags,
        duration_min=duration,
        price_per_person_sgd=price,
        hours=hours,
        diets_supported=set(diets or ()),
        serves_food=serves_food,
        wheelchair_accessible=wheelchair,
        step_free=step_free,
        crowd_estimate=crowd,
        indoor=indoor,
        weather_sensitive=weather,
        source=SOURCE,
        last_updated=updated,
        notes=notes,
    )



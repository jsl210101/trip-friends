def normalise_lang(lang: str | None) -> str:
    return "zh" if lang == "zh" else "en"


def t(key: str, lang: str | None = "en", **kwargs: object) -> str:
    """Look up a UI string. Chinese falls back to English, then to the key."""
    selected = ZH if normalise_lang(lang) == "zh" else EN
    template = selected.get(key) or EN.get(key) or key
    if not kwargs:
        return template
    return template.format(**kwargs)


def feature_name(feature: str, lang: str | None) -> str:
    return t(f"feature.{feature}", lang)


def catalogue_keys() -> tuple[set[str], set[str]]:
    return set(EN), set(ZH)


_REASON_CODES = {
    "it does not meet the group's dietary requirement": "diet",
    "it does not meet the group's accessibility requirement": "accessibility",
    "it is closed during the trip's days and hours": "hours",
    "its known price exceeds the group budget": "budget",
    "it is unsuitable in the selected heavy-rain scenario": "weather",
    "it was rejected for this plan": "rejected",
}


def reason_phrase(reason: str, lang: str | None) -> str:
    code = _REASON_CODES.get(reason, reason if reason in {
        "diet", "accessibility", "hours", "budget", "weather", "rejected"
    } else "")
    if code:
        return t(f"reason.{code}", lang)
    return reason


def floor_text(members: list[Member], utilities: list[float], beta: float, meets: bool, lang: str | None) -> str:
    if meets:
        return t("floor.met", lang, beta=beta)
    lines = [t("floor.miss", lang, beta=beta)]
    for member, utility in zip(members, utilities):
        if utility < beta:
            strong = [t(f"interest.{name}", lang) for name, value in member.preferences.items() if value >= 0.4]
            interests = ", ".join(strong) if strong else t("floor.none", lang)
            lines.append(t("floor.member", lang, name=member.name, utility=utility, interests=interests))
    lines.append(t("floor.advice", lang))
    return " ".join(lines)


def venue_caption(name: str, aliases: list[str], lang: str | None) -> str:
    """Show a Chinese catalogue alias beside the stored English name when useful."""
    if normalise_lang(lang) != "zh":
        return name
    for alias in aliases:
        if any("\u4e00" <= char <= "\u9fff" for char in alias) and alias not in name:
            return f"{name}（{alias}）"
    return name
